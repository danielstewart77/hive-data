"""Building a statement from declared names, never from caller-supplied ones.

Values travel as parameters. Column names cannot: there is no placeholder for
an identifier, so a statement whose column list came from a caller's keys has
caller-supplied text in its SQL. Every name used here is checked against the
declaration first, and anything else is refused rather than quoted and hoped
for.
"""

from __future__ import annotations

from typing import Any, Iterable, Mapping

from .errors import IdentityNotWritable, UnsettableColumn
from .rows import UNSET
from .schema import COLUMNS, GENERATED, qualified, qualified_name


def passed(values: Mapping[str, Any]) -> dict[str, Any]:
    """Only the parameters somebody actually passed.

    `UNSET` means "not mentioned" and is dropped; `None` means "write null"
    and is kept. Collapsing the two is how a column that must be cleared
    never gets cleared, and how a column that must be left alone gets
    blanked.
    """
    return {k: v for k, v in values.items() if v is not UNSET}


def _checked(table: str, names: Iterable[str], *,
             settable: frozenset[str] | None = None) -> list[str]:
    declared = COLUMNS[table]
    allowed = settable if settable is not None else frozenset(declared)
    where = qualified_name(table)
    out = []
    for name in names:
        if name not in allowed:
            known = "" if name in declared else (
                f" {where} has no column by that name.")
            raise UnsettableColumn(
                f"{where}.{name} is not settable through this "
                "operation.{known} Column names are not parameters, so the "
                "allowed ones are declared and anything else is refused "
                "rather than written into the statement: "
                f"{', '.join(sorted(allowed))}.".replace(
                    "{known}", known))
        out.append(name)
    return out


def insert(table: str, values: Mapping[str, Any], *,
           returning: tuple[str, ...] | None = None,
           on_conflict: str | None = None) -> tuple[str, list[Any]]:
    """An INSERT over the named columns, with its arguments."""
    generated = GENERATED.get(table, frozenset())
    named = [n for n in values]
    offending = [n for n in named if n in generated]
    if offending:
        raise IdentityNotWritable(
            f"{qualified_name(table)}.{offending[0]} is generated by the "
            "database. "
            "Postgres accepts a value on a GENERATED BY DEFAULT column and "
            "does not advance the sequence, so the row would land and the "
            "next insert would collide on it. Pass the row without it — "
            "round-tripping a row dict straight back into an insert is how "
            "this happens by accident.")
    columns = _checked(table, named)
    if not columns:
        raise UnsettableColumn(
            f"an insert into {qualified_name(table)} named no columns. An insert with "
            "an empty column list is a syntax error, not an empty row.")
    placeholders = ", ".join(f"${i}" for i in range(1, len(columns) + 1))
    quoted = ", ".join(f'"{c}"' for c in columns)
    sql = (f'INSERT INTO {qualified(table)} ({quoted}) '
           f'VALUES ({placeholders})')
    if on_conflict is not None:
        sql += f" {on_conflict}"
    if returning:
        sql += " RETURNING " + ", ".join(f'"{c}"' for c in returning)
    return sql, [values[c] for c in columns]


def update(table: str, values: Mapping[str, Any], where: Mapping[str, Any], *,
           settable: frozenset[str] | None = None,
           extra_where: str | None = None,
           returning: tuple[str, ...] | None = None,
           ) -> tuple[str, list[Any]]:
    """An UPDATE over the named columns, with its arguments.

    `settable` is the allow-list for this operation. The first consumer's
    dominant write is a dynamically assembled
    `UPDATE sessions SET {', '.join(assignments)}`, so an operation taking a
    field dict is the shape that is actually needed — and the allow-list is
    what keeps a caller's key out of the statement.
    """
    columns = _checked(table, list(values), settable=settable)
    if not columns:
        raise UnsettableColumn(
            f"an update of {qualified_name(table)} named no columns to set. An update "
            "with an empty SET is not a no-op, it is a syntax error.")
    args: list[Any] = []
    assignments = []
    for name in columns:
        args.append(values[name])
        assignments.append(f'"{name}" = ${len(args)}')
    conditions = []
    for name in _checked(table, list(where)):
        args.append(where[name])
        conditions.append(f'"{name}" = ${len(args)}')
    if extra_where:
        conditions.append(f"({extra_where})")
    sql = (f'UPDATE {qualified(table)} SET {", ".join(assignments)} '
           f'WHERE {" AND ".join(conditions)}')
    if returning:
        sql += " RETURNING " + ", ".join(f'"{c}"' for c in returning)
    return sql, args


def where(table: str, conditions: Mapping[str, Any],
          start: int = 1) -> tuple[str, list[Any]]:
    """A WHERE clause over declared columns, with its arguments.

    `None` becomes `IS NULL`, not `= NULL`. `= NULL` is never true, so the
    natural spelling of "only while this is still unset" would match nothing
    and report zero rows changed — which the caller reads as having lost a
    race it actually won, every time.
    """
    names = _checked(table, list(conditions))
    pieces: list[str] = []
    args: list[Any] = []
    for name in names:
        value = conditions[name]
        if value is None:
            pieces.append(f'"{name}" IS NULL')
            continue
        if value is UNSET:
            raise UnsettableColumn(
                f"{qualified_name(table)}.{name} was given UNSET as a condition. UNSET "
                "means nobody passed it, which is not something a row can "
                "be compared against. Leave it out, or pass None to mean "
                "IS NULL.")
        args.append(value)
        pieces.append(f'"{name}" = ${start + len(args) - 1}')
    return " AND ".join(pieces), args
