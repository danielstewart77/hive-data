"""What went wrong, in the words the caller has to act on.

A refusal is reported as a refusal, and two refusals with different remedies
are never the same exception. The hive already has the counter-example: an
unreachable inference proxy that yields an empty list reads exactly like a
proxy offering no models, and the operator is sent to rebuild an image for a
service that is simply down.

The taxonomy here is driven by what the first consumer actually branches on,
not by what a driver happens to raise:

* `Unreachable` and `CredentialRefused` are different machines to go and look
  at. Folding them together sends somebody to check an admin token they just
  used successfully.
* `TimedOut` and `NoConnectionAvailable` are neither of those. Left out of
  the taxonomy they become "unreachable", which is wrong in the one direction
  that matters: the database is up and answering everybody else.
* `Conflict` is separate from `MissingReference` because comms depends on the
  difference. `broker.add_message` is idempotent on purpose - the SMS gateway
  re-POSTs the same webhook on any non-2xx - so a duplicate delivery reported
  as a generic rejected write becomes a 500 and the gateway retries it
  forever. "That row already exists" and "that mind does not exist" drive
  different code.
"""

from __future__ import annotations


class HiveDataError(RuntimeError):
    """Base for everything this package raises deliberately."""


class NotInitialised(HiveDataError):
    """An operation ran before anything opened the pool.

    Its own error rather than a lazily-created pool: a lazy open under two
    concurrent first calls builds two pools and holds double the connections
    against a server-wide ceiling, with nothing reporting that it happened.
    """


class NotConfigured(HiveDataError):
    """No database was named, so there is nothing to connect to."""


class Unreachable(HiveDataError):
    """Nothing is listening, or the host is not there."""


class CredentialRefused(HiveDataError):
    """The database refused the credential offered."""


class DatabaseMissing(HiveDataError):
    """The server answered and does not have that database."""


class TimedOut(HiveDataError):
    """The database accepted the work and did not finish it in time."""


class NoConnectionAvailable(HiveDataError):
    """Every connection in the pool is busy and the deadline passed.

    Distinct from `TimedOut`: nothing was sent, so nothing is half-done, and
    the remedy is the pool's size rather than the statement.
    """


class WriteRejected(HiveDataError):
    """The database refused a write. Base for the constraint kinds below."""


class Conflict(WriteRejected):
    """A uniqueness or primary key the row would duplicate."""


class MissingReference(WriteRejected):
    """A foreign key naming a row that is not there."""


class ValueRefused(WriteRejected):
    """A check constraint, a not-null, or a type the column will not take."""


class TransactionAborted(HiveDataError):
    """The unit of work is already aborted; this statement was never looked at.

    Postgres aborts a whole transaction on the first error, so every
    statement after a handled failure is refused without being read. Its own
    class because the remedy is a savepoint around the recoverable part, not
    anything to do with the statement being reported — and calling it a
    rejected write blames a write the database never examined while the real
    cause has already been caught and discarded.
    """


class SequenceBehind(HiveDataError):
    """An identity sequence is behind the rows already in its table.

    What a bulk load leaves when it inserts explicit ids: Postgres accepts
    them on a `GENERATED BY DEFAULT` column without advancing the sequence.
    The next insert then collides on a key that is already there — and it
    collides as a uniqueness conflict, which is the one outcome a caller is
    told is benign and idempotent. A turn ledger silently recording nothing
    while reporting a harmless duplicate is the mind answering with no record
    of having been asked.
    """


class SchemaMismatch(HiveDataError):
    """The applied schema is not the one these operations were written for.

    Raised when the pool opens rather than at the call site. A column this
    package names and the database does not have otherwise arrives as a
    missing dict key, and the first consumer reads one of those as a value:
    `session.get("rotation_armed") or 0` is "nothing armed" on the single
    column whose three states decide whether a permanent session row is kept
    or retired.
    """


class UnsettableColumn(HiveDataError):
    """A partial update named a column it is not allowed to set.

    Column names cannot be parameterised, so an update assembled from
    caller-supplied keys puts caller-supplied *identifiers* into the SQL.
    Every settable column is declared, and anything else is refused here
    rather than interpolated.
    """


class IdentityNotWritable(HiveDataError):
    """An insert supplied a value for a generated identity column.

    Postgres accepts it on a `GENERATED BY DEFAULT` column and does not
    advance the sequence, so the row lands and plants a collision for whoever
    inserts next. Round-tripping a row dict back into an insert is the way
    that happens by accident.
    """


class TransactionMisuse(HiveDataError):
    """A unit of work was used in a way that cannot hold.

    Chiefly: held across a yield to the caller. `send_message` is an async
    generator that writes to the database inside its own `async for` over the
    model's response, so a transaction wrapped around it pins one pooled
    connection for the length of a turn - and a closed browser tab abandons
    the generator, leaving the transaction to unwind whenever the event
    loop's asyncgen finalizer gets to it.
    """
