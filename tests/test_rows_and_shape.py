"""What an operation hands back, and what it refuses to be handed."""

from __future__ import annotations

import json
import uuid

import pytest

import hive_data
from hive_data import core


async def test_a_row_survives_a_plain_json_encode(connected, a_mind):
    """asyncpg hands back `Record` objects, which `json.dumps` refuses. A
    service returning one would hand its web framework an object the
    framework's encoder cannot write."""
    mind = await core.get_mind(a_mind)

    assert isinstance(mind, dict)
    assert json.loads(json.dumps(mind))["mind_id"] == a_mind


async def test_a_read_matching_nothing_is_none_rather_than_an_error(connected):
    assert await core.get_mind("no-such-mind") is None


async def test_a_list_read_matching_nothing_is_an_empty_list(connected):
    assert await core.list_turns(f"no-such-session-{uuid.uuid4().hex}") == []


async def test_a_boolean_column_round_trips_as_it_was_written(
        connected, a_mind, clock, inspector):
    """`terminal_held` is a real boolean in the applied schema. Written True
    it must read True, and the row the database holds must say so too."""
    session_id = f"s-{uuid.uuid4().hex[:8]}"
    await core.create_session(
        id=session_id, surface="terminal", surface_id="tile-1",
        mind_id=a_mind, created_at=clock, last_active=clock)
    await core.update_session(session_id, terminal_held=True)

    assert (await core.get_session(session_id))["terminal_held"] is True
    assert await inspector.fetchval(
        'SELECT "terminal_held" FROM core."sessions" WHERE "id" = $1',
        session_id) is True


async def test_the_private_session_columns_are_withheld_unless_asked_for(
        connected, a_mind, clock):
    """A session listing answers to the service token every surface bot in
    the hive holds, and `carry_forward` is a composed system prompt."""
    session_id = f"s-{uuid.uuid4().hex[:8]}"
    await core.create_session(
        id=session_id, surface="telegram", surface_id="chat-1",
        mind_id=a_mind, created_at=clock, last_active=clock)
    await core.update_session(session_id, carry_forward="the whole soul")

    public = await core.get_session(session_id)
    private = await core.get_session(session_id, private=True)

    assert "carry_forward" not in public
    assert private["carry_forward"] == "the whole soul"


async def test_an_unset_parameter_is_not_the_same_as_an_explicit_null(
        connected, a_mind, clock, inspector):
    """Comms clears `harness_sid` deliberately so a failed turn cannot resume
    a broken thread, and separately omits columns it has no reading for.
    Collapsing the two means one of those never works."""
    session_id = f"s-{uuid.uuid4().hex[:8]}"
    await core.create_session(
        id=session_id, surface="telegram", surface_id="chat-1",
        mind_id=a_mind, created_at=clock, last_active=clock)
    await core.update_session(
        session_id, harness_sid="thread-abc", context_window=200_000)

    await core.update_session(session_id, harness_sid=None)

    row = await inspector.fetchrow(
        'SELECT "harness_sid", "context_window" FROM core."sessions" '
        'WHERE "id" = $1', session_id)
    assert row["harness_sid"] is None
    assert row["context_window"] == 200_000


async def test_an_update_naming_a_column_outside_the_allow_list_is_refused(
        connected, a_mind, clock):
    """Column names cannot be parameters, so a caller's keys must never reach
    the statement."""
    session_id = f"s-{uuid.uuid4().hex[:8]}"
    await core.create_session(
        id=session_id, surface="telegram", surface_id="chat-1",
        mind_id=a_mind, created_at=clock, last_active=clock)

    with pytest.raises(hive_data.UnsettableColumn):
        await core.update_session(session_id, id="somewhere-else")
    with pytest.raises(hive_data.UnsettableColumn):
        await core.update_session(
            session_id, **{'status" = \'x\' --': "injected"})


async def test_a_write_naming_a_generated_identity_is_refused(connected):
    """Postgres accepts a value on a GENERATED BY DEFAULT column without
    advancing the sequence, so the row lands and the next insert collides on
    it. Round-tripping a row dict straight back into an insert is how that
    happens by accident, so the builder refuses the column by name."""
    from hive_data import _sql

    with pytest.raises(hive_data.IdentityNotWritable):
        _sql.insert("session_turns", {
            "id": 7, "session_id": "s", "role": "user", "content": "c",
            "created_at": 1.0})

    sql, args = _sql.insert("session_turns", {
        "session_id": "s", "role": "user", "content": "c",
        "created_at": 1.0})
    assert '"id"' not in sql and len(args) == 4


async def test_a_written_turn_is_handed_the_identity_the_database_assigned(
        connected, a_mind, clock, inspector):
    """The caller deletes by that identity, so an operation that did not
    return it would leave them guessing."""
    session_id = f"s-{uuid.uuid4().hex[:8]}"
    await core.create_session(
        id=session_id, surface="telegram", surface_id="chat-1",
        mind_id=a_mind, created_at=clock, last_active=clock)

    result = await core.record_turn(
        session_id=session_id, role="user", content="hello", created_at=clock)

    assert result["rows"] == 1
    assert await inspector.fetchval(
        'SELECT "content" FROM core."session_turns" WHERE "id" = $1',
        result["row"]["id"]) == "hello"


async def test_a_value_carrying_a_quote_and_a_semicolon_is_stored_verbatim(
        connected, a_mind, clock, inspector):
    session_id = f"s-{uuid.uuid4().hex[:8]}"
    nasty = "it's fine; DROP TABLE core.sessions; --"
    await core.create_session(
        id=session_id, surface="telegram", surface_id="chat-1",
        mind_id=a_mind, created_at=clock, last_active=clock,
        opening_line=nasty)

    assert await inspector.fetchval(
        'SELECT "opening_line" FROM core."sessions" WHERE "id" = $1',
        session_id) == nasty
    assert await inspector.fetchval(
        "SELECT count(*) FROM core.\"sessions\"") >= 1
